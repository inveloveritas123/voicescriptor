"""Cookie-Harvester: Headless Firefox -> YouTube -> Cookies."""

import json
import logging
import time
from pathlib import Path
from datetime import datetime

logger = logging.getLogger(__name__)

COOKIE_PATH = Path("/app/data/cookies.txt")
HISTORY_PATH = Path("/app/data/cookie-history.json")
NETSCAPE_HEADER = "# Netscape HTTP Cookie File\n# Generated by VoiceScriptor Cookie Harvester\n\n"


def _cookies_to_netscape(cookies):
    lines = [NETSCAPE_HEADER]
    for c in cookies:
        domain = c.get("domain", "")
        if not domain.startswith("."):
            domain = "." + domain
        flag = "TRUE"
        path = c.get("path", "/")
        secure = "TRUE" if c.get("secure", False) else "FALSE"
        expires = c.get("expires", -1)
        if expires < 0:
            expires = int(time.time()) + 86400 * 30
        name = c.get("name", "")
        value = c.get("value", "")
        lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{int(expires)}\t{name}\t{value}")
    return "\n".join(lines)


def _save_history(method, count):
    hist = []
    if HISTORY_PATH.exists():
        try:
            hist = json.loads(HISTORY_PATH.read_text())
        except Exception:
            pass
    hist.append({
        "method": method,
        "entries": count,
        "timestamp": datetime.now().strftime("%d.%m.%Y %H:%M"),
    })
    HISTORY_PATH.write_text(json.dumps(hist[-20:]))


def harvest_with_playwright():
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return {"status": "error", "message": "Playwright nicht installiert"}

    logger.info("Cookie-Harvester: Starte Headless Firefox...")

    with sync_playwright() as p:
        browser = p.firefox.launch(headless=True)
        context = browser.new_context(
            viewport={"width": 1920, "height": 1080},
            locale="de-DE",
            timezone_id="Europe/Berlin",
            user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:134.0) Gecko/20100101 Firefox/134.0",
        )
        page = context.new_page()

        try:
            logger.info("Lade youtube.com...")
            page.goto("https://www.youtube.com", wait_until="domcontentloaded", timeout=30000)
            page.wait_for_timeout(2000)

            # GDPR Consent
            for selector in [
                'button[aria-label*="Alle akzeptieren"]',
                'button[aria-label*="Accept all"]',
                'button:has-text("Alle akzeptieren")',
                'button:has-text("Accept all")',
            ]:
                try:
                    btn = page.locator(selector).first
                    if btn.is_visible(timeout=1000):
                        btn.click()
                        logger.info("Consent akzeptiert")
                        page.wait_for_timeout(1500)
                        break
                except Exception:
                    continue

            # Surf-Verhalten simulieren
            page.mouse.wheel(0, 400)
            page.wait_for_timeout(1000)
            try:
                vl = page.locator("a#thumbnail[href*='watch']").first
                if vl.is_visible(timeout=3000):
                    vl.click()
                    page.wait_for_timeout(3000)
                    page.go_back()
                    page.wait_for_timeout(1500)
            except Exception:
                pass

            # Cookies extrahieren
            cookies = context.cookies()
            yt_cookies = [c for c in cookies if ".youtube.com" in c.get("domain", "") or ".google.com" in c.get("domain", "")]

            if not yt_cookies:
                return {"status": "error", "message": "Keine YouTube-Cookies generiert"}

            netscape = _cookies_to_netscape(yt_cookies)
            COOKIE_PATH.write_text(netscape, encoding="utf-8")
            _save_history("auto-harvest", len(yt_cookies))

            logger.info(f"Cookies gespeichert: {len(yt_cookies)} Eintraege")
            return {
                "status": "ok",
                "message": f"{len(yt_cookies)} frische YouTube-Cookies",
                "cookie_count": len(yt_cookies),
                "method": "playwright_firefox",
            }
        except Exception as e:
            logger.exception("Cookie-Harvester fehlgeschlagen")
            return {"status": "error", "message": str(e)[:200]}
        finally:
            context.close()
            browser.close()


if __name__ == "__main__":
    import logging
    logging.basicConfig(level=logging.INFO)
    print(json.dumps(harvest_with_playwright(), indent=2))
